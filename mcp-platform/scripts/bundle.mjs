#!/usr/bin/env node
/**
 * Builds the single-file server shipped by the Windows installer.
 *
 *   node scripts/bundle.mjs [--out <dir>]      (run `npm run build` first)
 *
 * Every tool package under packages/tools/* that declares "lmpTool" is compiled into the server
 * and registered as a built-in, so the shipped server is one JavaScript file with exactly one copy
 * of @lmp/core, the toolkit and zod (no node_modules folder to install or scan). Adding a tool
 * package needs no change here: the entry is generated from the packages found.
 *
 * Output (default: release/payload):
 *   server/server.mjs           the server (stdio MCP)
 *   server/THIRD_PARTY_NOTICES.txt
 *   server/manifest.json        version, tool packages, sha-256 of server.mjs
 */
import { createHash } from "node:crypto";
import { mkdir, mkdtemp, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outArg = process.argv.indexOf("--out");
const outDir = path.resolve(outArg > 0 ? process.argv[outArg + 1] : path.join(root, "release", "payload"));

const toolsRoot = path.join(root, "packages", "tools");
const tools = [];
for (const name of (await readdir(toolsRoot)).sort()) {
  const manifestFile = path.join(toolsRoot, name, "package.json");
  const pkg = JSON.parse(await readFile(manifestFile, "utf8").catch(() => "{}"));
  if (!pkg.lmpTool) continue;
  const entry = path.join(toolsRoot, name, pkg.lmpTool.entry);
  if (!(await stat(entry).catch(() => null))) throw new Error(`${entry} is missing; run "npm run build" first.`);
  tools.push({ id: pkg.lmpTool.id, entry });
}
const cliMain = path.join(root, "packages", "server", "dist", "src", "cli-main.js");
if (!(await stat(cliMain).catch(() => null))) throw new Error(`${cliMain} is missing; run "npm run build" first.`);

const work = await mkdtemp(path.join(os.tmpdir(), "lmp-bundle-"));
try {
  const entryFile = path.join(work, "entry.mjs");
  const spec = (file) => JSON.stringify(file.replace(/\\/g, "/"));
  const lines = [
    "// Generated by scripts/bundle.mjs",
    `import { runCli } from ${spec(cliMain)};`,
    ...tools.map((t, i) => `import tool${i} from ${spec(t.entry)};`),
    `runCli([${tools.map((t, i) => `{ pkg: tool${i}, location: ${JSON.stringify(`bundled:${t.id}`)} }`).join(", ")}]);`,
  ];
  await writeFile(entryFile, lines.join("\n") + "\n");

  await rm(path.join(outDir, "server"), { recursive: true, force: true });
  await mkdir(path.join(outDir, "server"), { recursive: true });
  const outfile = path.join(outDir, "server", "server.mjs");
  const result = await build({
    entryPoints: [entryFile],
    outfile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    // Readable output: the shipped code can be audited as-is.
    minify: false,
    legalComments: "none",
    metafile: true,
    logLevel: "warning",
    absWorkingDir: root,
    nodePaths: [path.join(root, "node_modules")],
    banner: {
      js: [
        "#!/usr/bin/env node",
        "// Local MCP Platform server (bundled). Third-party notices: THIRD_PARTY_NOTICES.txt",
        'import { createRequire as __lmpCreateRequire } from "node:module";',
        "const require = __lmpCreateRequire(import.meta.url);",
      ].join("\n"),
    },
  });

  // Licences of every third-party package that ended up in the bundle.
  const packagesUsed = new Map();
  for (const input of Object.keys(result.metafile.inputs)) {
    const m = /node_modules[\\/]((?:@[^\\/]+[\\/])?[^\\/]+)/.exec(input);
    if (!m) continue;
    const name = m[1].replace(/\\/g, "/");
    if (name.startsWith("@lmp/")) continue;
    packagesUsed.set(name, path.join(root, "node_modules", name));
  }
  const notices = [];
  for (const [name, dir] of [...packagesUsed].sort(([a], [b]) => a.localeCompare(b))) {
    const meta = JSON.parse(await readFile(path.join(dir, "package.json"), "utf8"));
    const files = await readdir(dir);
    const licenseFile = files.find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
    const text = licenseFile ? await readFile(path.join(dir, licenseFile), "utf8") : `License: ${meta.license ?? "see package"}`;
    notices.push(`${"=".repeat(78)}\n${name}@${meta.version} (${meta.license ?? "unknown"})\n${"=".repeat(78)}\n${text.trim()}\n`);
  }
  await writeFile(path.join(outDir, "server", "THIRD_PARTY_NOTICES.txt"), notices.join("\n").replace(/\r?\n/g, "\r\n"));

  const code = await readFile(outfile);
  const product = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
  const manifest = {
    product: product.name,
    version: product.version,
    node: ">=22.12.0",
    tools: tools.map((t) => t.id),
    thirdParty: [...packagesUsed.keys()].sort(),
    serverSha256: createHash("sha256").update(code).digest("hex"),
    bytes: code.length,
  };
  await writeFile(path.join(outDir, "server", "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  console.log(`bundle: ${path.relative(root, outfile)} ${(code.length / 1024).toFixed(0)} KiB, ${tools.length} tool packages, ${packagesUsed.size} third-party packages`);
} finally {
  await rm(work, { recursive: true, force: true });
}
